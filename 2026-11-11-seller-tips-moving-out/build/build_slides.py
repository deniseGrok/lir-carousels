def build_no_pdf(fmt, only=None):
    """Native Signature Authority rendering; deliberately never creates a PDF."""
    import zipfile
    from PIL import Image, ImageFilter
    w,h = sa.FMTS[fmt]
    idir = os.path.join(B, "img" if fmt == "4x5" else f"img-{fmt}")
    od = D if fmt == "4x5" else os.path.join(D, f"slides-{fmt}")
    sfx = "" if fmt == "4x5" else f"-{fmt}"
    os.makedirs(idir,exist_ok=True); os.makedirs(od,exist_ok=True)
    for n,sd in enumerate(SL,1):
        if only and n not in only: continue
        x,y=sd.get(f"xy_{fmt}",sd.get("xy",(.5,.5)))
        if (fmt == "4x5" or sd.get("bright_all")) and sd["kind"] in sa.BRIGHT and sd.get("photo") and not sd.get("legacy"):
            ph=sa.crisp(sa.crop(os.path.join(B,"src",sd["photo"]),w,h,x,y,sd.get("pre")),**sd.get("crisp",{}))
            ph.save(os.path.join(idir,f"{n:02d}.png"))
            hi,extra=sa.inner(sd,n,len(SL),"seller",None);o=sa.OVR.get(fmt,{})
            extra+=(sa.BRIGHT[sd["kind"]]+o.get("all","")+o.get(sd["kind"],"")+sa.BRIGHT_FMT.get(fmt,{}).get(sd["kind"],"")+sd.get(f"css_{fmt}","")+sa.CLEAR)
            hp=os.path.join(B,f"slide-{n:02d}{sfx}.html");open(hp,"w").write(sa.page(hi,extra,w,h))
            lay=os.path.join(B,f"layer-{n:02d}.png");sa.render(hp,lay,w,h,scale=2,transparent=True)
            layer=Image.open(lay).convert("RGBa").resize((w,h),Image.Resampling.LANCZOS).convert("RGBA");os.remove(lay)
            out=ph.convert("RGBA");out.alpha_composite(layer);out.convert("RGB").save(os.path.join(od,f"slide-{n:02d}.png"))
        else:
            img=None
            if sd.get("photo"):
                img=os.path.join(idir,f"{n:02d}.jpg")
                im=sa.warm(sa.crop(os.path.join(B,"src",sd["photo"]),w,h,x,y,sd.get("pre")),**sd.get("grade",{}))
                if sd.get("blur"):im=im.filter(ImageFilter.GaussianBlur(sd["blur"]))
                im.save(img,quality=92)
            hi,extra=sa.inner(sd,n,len(SL),"seller",img);o=sa.OVR.get(fmt,{})
            extra+=o.get("all","")+o.get(sd["kind"],"")+sd.get(f"css_{fmt}","")
            hp=os.path.join(B,f"slide-{n:02d}{sfx}.html");open(hp,"w").write(sa.page(hi,extra,w,h))
            sa.render(hp,os.path.join(od,f"slide-{n:02d}.png"),w,h)
        print(fmt,n,flush=True)
    zp="slides.zip" if fmt=="4x5" else f"slides-{fmt}.zip"
    with zipfile.ZipFile(os.path.join(D,zp),"w") as z:
        for n in range(1,11):z.write(os.path.join(od,f"slide-{n:02d}.png"),f"slide-{n:02d}.png")

if __name__ == "__main__":
    for fmt in (sys.argv[1:] or ("4x5","1x1","9x16")):build_no_pdf(fmt)
